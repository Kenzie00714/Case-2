"""Bundle data/, content/ and params into web/data.js for the browser game.
Re-run after changing any CSV, the scenario content, or zombie_sim/params.py."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from zombie_sim.data_loader import load_world
from zombie_sim.attributes import load_attributes, load_content, CONTENT
from zombie_sim.engine import load_fallbacks
from zombie_sim.params import PARAMS, MINIGAMES, MINIGAME_ORDER, CURE_FLAGS


def read_csv(name):
    import csv
    path = os.path.join(ROOT, "data", name)
    if not os.path.exists(path):
        return []
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def bundle():
    w = load_world()
    return {"params": PARAMS, "minigames": MINIGAMES, "minigame_order": MINIGAME_ORDER, "cure_flags": CURE_FLAGS,
            "world": w, "content": load_content(os.path.join(CONTENT, "scenarios_v2.json")), "attrs": load_attributes(), "fallbacks": load_fallbacks(),
            "reference": {"r0": read_csv("r0_reference.csv"), "rabies": read_csv("rabies_reference.csv")}}


if __name__ == "__main__":
    b = bundle()
    path = os.path.join(ROOT, "web", "data.js")
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_web.py from data/*.csv, content/ and zombie_sim/params.py. Do not edit by hand.\n")
        f.write("window.GAME_DATA = " + json.dumps(b, ensure_ascii=False, separators=(",", ":")) + ";\n")
    with open(os.path.join(ROOT, "tests", "bundle.json"), "w", encoding="utf-8") as f:
        json.dump(b, f, ensure_ascii=False)
    print(f"Wrote {path} ({os.path.getsize(path) / 1024:.0f} KB)")
